#!/usr/bin/env node
/**
 * Creates the ECDSA P-256 key pair that signs license replies.
 *
 *   node tools/gen-server-keys.mjs            create the pair
 *   node tools/gen-server-keys.mjs --force    replace an existing pair
 *
 * It prints the PRIVATE key ONCE (paste it into `wrangler secret put
 * LICENSE_SIGNING_KEY`), writes the matching public key into the Android app,
 * and writes a local-only `.dev.vars` so `wrangler dev` can sign replies while
 * you test on this PC.
 *
 * The private key is never written into the app, the repository or dist/.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";

const here = dirname(fileURLToPath(import.meta.url));
const serverDir = resolve(here, "..");
const projectRoot = resolve(serverDir, "..");
const publicKeySource = join(
  projectRoot,
  "app/src/main/java/com/textpic/studio/data/license/LicenseServerPublicKey.kt",
);

function b64(der) {
  return Buffer.from(der).toString("base64");
}

function pem(label, der) {
  const body = b64(der).match(/.{1,64}/g).join("\n");
  return `-----BEGIN ${label}-----\n${body}\n-----END ${label}-----\n`;
}

const force = process.argv.includes("--force");
const skipDevVars = process.argv.includes("--no-dev-vars");

if (existsSync(publicKeySource) && !force) {
  console.log("A public key already exists at:");
  console.log("  " + publicKeySource);
  console.log("");
  console.log("Refusing to replace it: activation keys signed with the current");
  console.log("private key would stop working in already installed apps.");
  console.log("Pass --force only if you really want a new key pair.");
  process.exit(0);
}

const pair = await crypto.subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, [
  "sign",
  "verify",
]);
const pkcs8 = new Uint8Array(await crypto.subtle.exportKey("pkcs8", pair.privateKey));
const spki = new Uint8Array(await crypto.subtle.exportKey("spki", pair.publicKey));
const privatePem = pem("PRIVATE KEY", pkcs8);
const publicBase64 = b64(spki);

mkdirSync(dirname(publicKeySource), { recursive: true });
writeFileSync(
  publicKeySource,
  `package com.textpic.studio.data.license

/**
 * Public key the app uses to check that a license reply really came from the
 * owner's server. ECDSA P-256, X.509 SubjectPublicKeyInfo, Base64.
 *
 * GENERATED by server/tools/gen-server-keys.mjs - do not edit by hand.
 * The matching private key lives only in the Cloudflare Worker secret.
 */
object LicenseServerPublicKey {
    const val ENCODED: String = "${publicBase64}"
}
`,
  "utf8",
);

const devVarsPath = join(serverDir, ".dev.vars");
if (!skipDevVars) {
  const adminToken = randomBytes(24).toString("base64url");
  writeFileSync(
    devVarsPath,
    [
      "# LOCAL TESTING ONLY - never commit, never deploy these values.",
      "# Generated by tools/gen-server-keys.mjs for `wrangler dev`.",
      `ADMIN_TOKEN="${adminToken}"`,
      `LICENSE_SIGNING_KEY="${privatePem.trim()}"`,
      'QUOTA_TZ="UTC"',
      "",
    ].join("\n"),
    "utf8",
  );
}

console.log("New signing key pair created.");
console.log("");
console.log("1) Public key written to:");
console.log("   " + publicKeySource);
console.log("   (rebuild the app: ./gradlew assembleRelease)");
console.log("");
console.log("2) Store the PRIVATE key as a Worker secret. Run this in server/ and");
console.log("   paste the block below when it asks for the value:");
console.log("");
console.log("     npx wrangler secret put LICENSE_SIGNING_KEY");
console.log("");
console.log("----- private key (keep it safe, never send it to a customer) -----");
console.log(privatePem.trim());
console.log("-------------------------------------------------------------------");
console.log("");
if (!skipDevVars) {
  console.log("3) Local testing file written (gitignored, PC only):");
  console.log("   " + devVarsPath);
  console.log("   It holds this same private key so `npx wrangler dev` can sign");
  console.log("   replies while you test. Delete the file before lending the PC.");
  console.log("");
}
console.log("Back up the private key somewhere safe (password manager / USB stick).");
console.log("If you lose it, every installed app must be replaced with a new build.");
if (!existsSync(join(serverDir, "node_modules"))) {
  console.log("");
  console.log("Tip: run `npm install` in server/ first.");
}
